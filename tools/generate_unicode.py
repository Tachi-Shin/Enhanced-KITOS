#!/usr/bin/env python3
"""Generate one-codepoint Unicode uppercase data used for FAT name comparison."""
import unicodedata
from pathlib import Path
pairs = []
for cp in range(0x110000):
    upper = chr(cp).upper()
    if len(upper) == 1 and ord(upper) != cp:
        pairs.append((cp, ord(upper)))
ranges, singles = [], []
i = 0
while i < len(pairs):
    j = i + 1
    delta = pairs[i][1] - pairs[i][0]
    while j < len(pairs) and pairs[j][0] == pairs[j - 1][0] + 1 and pairs[j][1] - pairs[j][0] == delta:
        j += 1
    if j - i > 1: ranges.append((pairs[i][0], pairs[j - 1][0], delta))
    else: singles.append(pairs[i])
    i = j
out = ['/* Generated by tools/generate_unicode.py; Unicode ' + unicodedata.unidata_version + '. */',
       'static const struct { uint32_t first, last; int32_t delta; } upper_ranges[] = {']
out += [f'    {{0x{a:X}, 0x{b:X}, {d}}},' for a, b, d in ranges]
out += ['};', 'static const struct { uint32_t lower, upper; } upper_pairs[] = {']
for i in range(0, len(singles), 4):
    out.append('    ' + ' '.join(f'{{0x{a:X}, 0x{b:X}}},' for a, b in singles[i:i+4]))
out += ['};', 'static const uint16_t cp437_high[128] = {']
for i in range(128, 256, 8):
    out.append('    ' + ', '.join(f'0x{ord(bytes([c]).decode("cp437")):04X}' for c in range(i, i+8)) + ',')
out += ['};', '']
Path(__file__).resolve().parent.parent.joinpath('lib/unicode_data.h').write_text('\n'.join(out))
